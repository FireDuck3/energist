// Помилки запиту бронювання (request_pilot_booking) для вікна бронювання. Чисті функції без DOM.

// Ліміти проти захоплення слотів ботами (міграція 202611240005_booking_limits.sql; числа мають збігатися):
// pending — скільки запитів, що чекають відповіді господаря, може мати гість одночасно;
// perDay — скільки запитів на бронювання гість може надіслати за 24 години (разом зі скасованими).
export const BOOKING_LIMITS = { pending: 3, perDay: 10 };

const GENERIC = 'Не вдалося надіслати запит. Перевірте час і спробуйте ще раз.';

// Перетин бронювань (23P01) вікно обробляє окремо — перезавантажує вільний час.
export function bookingRequestError(error) {
  if (error?.code === 'WW429' && error.message === 'pending_limit') {
    return `У вас уже ${BOOKING_LIMITS.pending} запити, що чекають відповіді господаря. Дочекайтеся відповіді або скасуйте один із них у «Мої бронювання».`;
  }
  if (error?.code === 'WW429' && error.message === 'daily_limit') {
    return `Ви надіслали ${BOOKING_LIMITS.perDay} запитів на бронювання за добу — це максимум. Спробуйте пізніше.`;
  }
  return GENERIC;
}
