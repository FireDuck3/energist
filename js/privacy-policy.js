const blocksOf = (section) => (typeof section.body === 'function' ? section.body() : section.body)
  .map((b) => (typeof b === 'function' ? b() : b));

export function sectionBlocks(section) {
  return blocksOf(section);
}

// Увесь текст політики одним рядком — для перевірок (тести не пропускають заборонених обіцянок).
export function policyText() {
  const flat = (x) => (Array.isArray(x) ? x.map(flat).join('') : typeof x === 'string' ? x : x?.text ?? '');
  const block = (b) => (b.list ? b.list.map(flat).join('\n') : b.h3 ?? flat(b));
  return SECTIONS.map((s) => [s.title, ...blocksOf(s).map(block)].join('\n')).join('\n\n');
}
